leitor = input('digite algo:')
print(type(leitor))
print(leitor.isalpha()) # verifica se leitor é uma alfabético, se for retorna True, se não retorna False.
print(leitor.isnumeric()) # verifica se leitor é um número, se for retorna True, se não retorna False.
print(leitor.isalnum()) # verifica se leitor é alfanumérico, se for retorna True, se não retorna False.
print(leitor.isupper()) # verifica se leitor está em maiúsculas, se for retorna True, se não retorna False.
print(leitor.isdecimal()) # verifica se leitor é um decimal, se for retorna True, se não retorna False.
print(leitor.islower()) # verifica se leitor está em minúsculas, se for retorna True, se não retorna False.
print(leitor.istitle()) # verifica se leitor está no formato de título, se for retorna True, se não retorna False.
print(leitor.isprintable()) # verifica se leitor é imprimível, se for retorna True, se não retorna False.



