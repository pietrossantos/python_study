# Faça um programa que leia um número inteiro e exiba na tela o seu sucessor e seu antecessor

num = int(input('digite um número:'))
sucessor = num +1
antecessor = num -1

print(f'Seu número é: {num}, seu sucessor é:\n{sucessor}\ne o seu antecessor é:\n{antecessor}')

