# Crie um algoritmo que mostre o seu dobro, triplo e sua raiz quadrada

num = float(input('digite um número gafanhoto:'))
raiz = num**0.5
dobro = num*2
triplo = num*3

print(f'O dobro é: {dobro}, o triplo é: {triplo}, e a raiz é: {raiz}')

